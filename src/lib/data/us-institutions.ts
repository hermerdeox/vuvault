/**
 * Filter the institution list for a typeahead.
 *
 * Ranking: prefix matches first (alphabetical), then substring
 * matches (alphabetical). Case- and whitespace-insensitive. With an
 * empty query, returns the head of the list (the largest
 * institutions) so the dropdown is useful on first focus.
 */
export function searchInstitutions(query: string, limit = 10): string[] {
	const q = query.trim().toLowerCase();
	if (!q) return US_INSTITUTIONS.slice(0, limit);

	const prefix: string[] = [];
	const substring: string[] = [];
	for (const name of US_INSTITUTIONS) {
		const lower = name.toLowerCase();
		if (lower.startsWith(q)) prefix.push(name);
		else if (lower.includes(q)) substring.push(name);
	}
	prefix.sort((a, b) => a.localeCompare(b));
	substring.sort((a, b) => a.localeCompare(b));
	return [...prefix, ...substring].slice(0, limit);
}
